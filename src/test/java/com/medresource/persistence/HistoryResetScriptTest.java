package com.medresource.persistence;

import org.junit.jupiter.api.Test;

import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.util.List;
import java.util.regex.Pattern;

import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

/** Verificaciones estáticas del reinicio manual; estas pruebas nunca borran datos en Oracle. */
class HistoryResetScriptTest {

    private static String resource(String path) throws IOException {
        try (InputStream stream = HistoryResetScriptTest.class.getResourceAsStream(path)) {
            assertNotNull(stream, "No se encontró " + path);
            return new String(stream.readAllBytes(), StandardCharsets.UTF_8);
        }
    }

    @Test
    void resetStartsDisabledAndRequiresExplicitConfirmation() throws IOException {
        String script = resource("/db/reiniciar_historial_demostracion.sql");
        assertTrue(script.contains("v_confirmacion CONSTANT VARCHAR2(30) := 'NO';"));
        assertTrue(script.contains("IF v_confirmacion <> 'BORRAR_HISTORIAL' THEN"));
        assertTrue(script.contains("RAISE_APPLICATION_ERROR(-20980"));
        assertFalse(script.toUpperCase().contains("DROP TABLE"));
        assertFalse(script.toUpperCase().contains("TRUNCATE TABLE"));
    }

    @Test
    void resetKeepsDiseaseCatalogAndRestartsOnlyHistoricalIdentities() throws IOException {
        String script = resource("/db/reiniciar_historial_demostracion.sql").toUpperCase();
        for (String table : List.of("COMPARACION", "REPORTE", "EVENTO", "RESULTADO_PACIENTE",
                "EJECUCION_MEDICO_EXTRA", "EJECUCION", "CASO_PACIENTE_SINTOMA",
                "CASO_PACIENTE", "CASO", "AUDITORIA_REPORTE")) {
            assertTrue(Pattern.compile("(?m)^\\s*DELETE FROM " + table + ";$").matcher(script).find(), table);
        }
        for (String table : List.of("CASO", "EJECUCION", "REPORTE", "COMPARACION", "AUDITORIA_REPORTE")) {
            assertTrue(script.contains("ALTER TABLE " + table + " MODIFY (ID GENERATED BY DEFAULT AS IDENTITY "
                    + "(START WITH 1 NOCACHE))"), table);
        }
        assertFalse(Pattern.compile("(?m)^\\s*DELETE FROM ENFERMEDAD(?:_SINTOMA|_ESPECIALIDAD_SEC)?\\s*;")
                .matcher(script).find());
    }

    @Test
    void newSchemasAvoidCacheForTheFiveHistoricalIds() throws IOException {
        String schema = resource("/db/schema.sql");
        for (String name : List.of("caso", "ejecucion", "reporte", "comparacion", "auditoria_reporte")) {
            assertTrue(schema.contains("CREATE TABLE " + name + " ("), name);
        }
        assertTrue(Pattern.compile("GENERATED BY DEFAULT AS IDENTITY \\(START WITH 1 NOCACHE\\)")
                .matcher(schema).results().count() == 5);
    }
}
