-- MedResource AI - REINICIO MANUAL Y DESTRUCTIVO DEL HISTORIAL (Oracle 18c XE).
-- NO lo ejecuta Java, Maven ni las migraciones automaticas.
-- SOLO en un esquema de prueba, tras guardar una copia de seguridad.
-- Borra de forma IRREVERSIBLE casos, pacientes generados, ejecuciones, resultados,
-- eventos, reportes, comparaciones y auditorias de reportes.
-- CONSERVA enfermedad y sus catalogos, funciones, procedimientos, triggers e indices.
-- Para autorizarlo, cambiar el valor NO por BORRAR_HISTORIAL y ejecutar TODO con F5.
-- El cambio NO/BORRAR_HISTORIAL es una proteccion contra ejecuciones accidentales.
-- Ejecutarlo despues de las pruebas Maven, que tambien pueden consumir IDs.
-- Oracle IDENTITY no garantiza numeracion sin huecos tras rollbacks o intentos fallidos.

SET SERVEROUTPUT ON

DECLARE
    v_confirmacion CONSTANT VARCHAR2(30) := 'NO';
    v_identidades NUMBER;
    v_tablas NUMBER;
BEGIN
    IF v_confirmacion <> 'BORRAR_HISTORIAL' THEN
        RAISE_APPLICATION_ERROR(-20980,
            'Proteccion: no se borraron datos. Cambie NO por BORRAR_HISTORIAL para confirmar.');
    END IF;

    -- No ejecutar sobre un esquema incompleto o distinto al del proyecto.
    SELECT COUNT(*) INTO v_identidades
    FROM USER_TAB_IDENTITY_COLS
    WHERE COLUMN_NAME = 'ID'
      AND TABLE_NAME IN ('CASO', 'EJECUCION', 'REPORTE', 'COMPARACION', 'AUDITORIA_REPORTE');
    IF v_identidades <> 5 THEN
        RAISE_APPLICATION_ERROR(-20981, 'No se encuentran las cinco columnas IDENTITY esperadas.');
    END IF;

    SELECT COUNT(*) INTO v_tablas
    FROM USER_TABLES
    WHERE TABLE_NAME IN ('CASO', 'CASO_PACIENTE', 'CASO_PACIENTE_SINTOMA',
        'EJECUCION', 'EJECUCION_MEDICO_EXTRA', 'RESULTADO_PACIENTE',
        'EVENTO', 'REPORTE', 'COMPARACION', 'AUDITORIA_REPORTE');
    IF v_tablas <> 10 THEN
        RAISE_APPLICATION_ERROR(-20982, 'El esquema no contiene todas las tablas historicas esperadas.');
    END IF;

    -- Hojas primero: se respetan las FK, incluso si cambian reglas ON DELETE.
    DELETE FROM comparacion;
    DELETE FROM reporte;
    DELETE FROM evento;
    DELETE FROM resultado_paciente;
    DELETE FROM ejecucion_medico_extra;
    DELETE FROM ejecucion;
    DELETE FROM caso_paciente_sintoma;
    DELETE FROM caso_paciente;
    DELETE FROM caso;
    DELETE FROM auditoria_reporte;
    COMMIT;

    -- Reiniciar las cinco identidades; solo cuando las tablas ya estan vacias.
    -- NOCACHE reduce los saltos por perdida de cache, NO impide huecos por rollback.
    EXECUTE IMMEDIATE 'ALTER TABLE caso MODIFY (id GENERATED BY DEFAULT AS IDENTITY (START WITH 1 NOCACHE))';
    EXECUTE IMMEDIATE 'ALTER TABLE ejecucion MODIFY (id GENERATED BY DEFAULT AS IDENTITY (START WITH 1 NOCACHE))';
    EXECUTE IMMEDIATE 'ALTER TABLE reporte MODIFY (id GENERATED BY DEFAULT AS IDENTITY (START WITH 1 NOCACHE))';
    EXECUTE IMMEDIATE 'ALTER TABLE comparacion MODIFY (id GENERATED BY DEFAULT AS IDENTITY (START WITH 1 NOCACHE))';
    EXECUTE IMMEDIATE 'ALTER TABLE auditoria_reporte MODIFY (id GENERATED BY DEFAULT AS IDENTITY (START WITH 1 NOCACHE))';

    DBMS_OUTPUT.PUT_LINE('Historial vacio e identidades reiniciadas desde 1.');
    DBMS_OUTPUT.PUT_LINE('Catalogo de enfermedades intacto.');
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
END;
/

-- Comprobacion posterior (debe devolver ceros en las tablas historicas).
SELECT 'CASO' AS TABLA, COUNT(*) AS FILAS FROM CASO
UNION ALL SELECT 'EJECUCION', COUNT(*) FROM EJECUCION
UNION ALL SELECT 'REPORTE', COUNT(*) FROM REPORTE
UNION ALL SELECT 'COMPARACION', COUNT(*) FROM COMPARACION
UNION ALL SELECT 'AUDITORIA_REPORTE', COUNT(*) FROM AUDITORIA_REPORTE;
